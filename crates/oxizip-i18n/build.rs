//! Scan `locales/*.toml` and embed them. Adding a language = drop a new TOML file.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let locales_dir = manifest_dir.join("locales");
    println!("cargo:rerun-if-changed={}", locales_dir.display());

    let mut files: Vec<PathBuf> = fs::read_dir(&locales_dir)
        .unwrap_or_else(|e| panic!("read locales/: {e}"))
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| {
            p.extension()
                .and_then(|e| e.to_str())
                .is_some_and(|e| e.eq_ignore_ascii_case("toml"))
        })
        .collect();
    files.sort();
    if files.is_empty() {
        panic!("no locales/*.toml found under {}", locales_dir.display());
    }

    for f in &files {
        println!("cargo:rerun-if-changed={}", f.display());
    }

    let locales: Vec<Locale> = files.iter().map(|p| parse_locale_toml(p)).collect();

    let mut out = String::from(
        "// @generated by oxizip-i18n/build.rs — do not edit.\n\n\
         #[allow(dead_code)]\n\
         pub struct LocaleData {\n\
             pub code: &'static str,\n\
             pub cli: &'static str,\n\
             pub native: &'static str,\n\
             pub messages: &'static [(&'static str, &'static str)],\n\
         }\n\n",
    );

    out.push_str("pub static LOCALES: &[LocaleData] = &[\n");
    for loc in &locales {
        out.push_str("    LocaleData {\n");
        out.push_str(&format!("        code: {},\n", rust_str(&loc.code)));
        out.push_str(&format!("        cli: {},\n", rust_str(&loc.cli)));
        out.push_str(&format!("        native: {},\n", rust_str(&loc.native)));
        out.push_str("        messages: &[\n");
        for (k, v) in &loc.messages {
            out.push_str(&format!(
                "            ({}, {}),\n",
                rust_str(k),
                rust_str(v)
            ));
        }
        out.push_str("        ],\n");
        out.push_str("    },\n");
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("locales_generated.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("write {}: {e}", dest.display()));
}

struct Locale {
    code: String,
    cli: String,
    native: String,
    messages: BTreeMap<String, String>,
}

fn parse_locale_toml(path: &Path) -> Locale {
    let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let value = text
        .parse::<toml::Value>()
        .unwrap_or_else(|e| panic!("parse {}: {e}", path.display()));
    let table = value
        .as_table()
        .unwrap_or_else(|| panic!("{}: root must be a table", path.display()));

    let code = table
        .get("code")
        .and_then(|v| v.as_str())
        .unwrap_or_else(|| panic!("{}: missing string `code`", path.display()))
        .to_string();
    let cli = table
        .get("cli")
        .and_then(|v| v.as_str())
        .unwrap_or(code.as_str())
        .to_string();
    let native = table
        .get("native")
        .and_then(|v| v.as_str())
        .unwrap_or_else(|| panic!("{}: missing string `native`", path.display()))
        .to_string();

    let messages_val = table
        .get("messages")
        .unwrap_or_else(|| panic!("{}: missing [messages]", path.display()));
    let messages_table = messages_val
        .as_table()
        .unwrap_or_else(|| panic!("{}: [messages] must be a table", path.display()));

    let mut messages = BTreeMap::new();
    for (k, v) in messages_table {
        let s = v
            .as_str()
            .unwrap_or_else(|| panic!("{}: messages.{} must be a string", path.display(), k));
        messages.insert(k.clone(), s.to_string());
    }
    if messages.is_empty() {
        panic!("{}: [messages] is empty", path.display());
    }

    Locale {
        code,
        cli,
        native,
        messages,
    }
}

fn rust_str(s: &str) -> String {
    format!("\"{}\"", s.escape_default())
}
